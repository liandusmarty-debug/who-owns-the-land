"""Source registry: what we downloaded, from where, when, under which licence, with checksums."""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass
from datetime import date
from pathlib import Path

from .config import SourceSpec


@dataclass(slots=True)
class SourceRecord:
    id: str
    title: str
    publisher: str
    licence: str
    url: str
    retrieved: str
    files: dict[str, str]  # relative path -> sha256
    notes: str = ""


def sha256(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


class SourceLog:
    """Persists data/raw/manifest.json and renders sources.md from it."""

    def __init__(self, raw_dir: Path) -> None:
        self.raw_dir = raw_dir
        self.manifest_path = raw_dir / "manifest.json"
        self.records: dict[str, SourceRecord] = {}
        if self.manifest_path.exists():
            for r in json.loads(self.manifest_path.read_text(encoding="utf-8")):
                self.records[r["id"]] = SourceRecord(**r)

    def record(self, spec: SourceSpec, folder: Path, retrieved: str | None = None) -> SourceRecord:
        files = {
            str(p.relative_to(self.raw_dir)): sha256(p)
            for p in sorted(folder.rglob("*"))
            if p.is_file()
        }
        prev = self.records.get(spec.id)
        rec = SourceRecord(
            id=spec.id,
            title=spec.title,
            publisher=spec.publisher,
            licence=spec.licence,
            url=spec.url,
            # keep the original retrieval date if files are unchanged
            retrieved=prev.retrieved if prev and prev.files == files else (retrieved or date.today().isoformat()),
            files=files,
            notes=spec.notes,
        )
        self.records[spec.id] = rec
        return rec

    def save(self) -> None:
        self.raw_dir.mkdir(parents=True, exist_ok=True)
        self.manifest_path.write_text(
            json.dumps([asdict(r) for r in self.records.values()], indent=2), encoding="utf-8"
        )

    def render_markdown(self) -> str:
        lines = [
            "# Data sources",
            "",
            "_Generated by the pipeline from `data/raw/manifest.json`. Do not edit by hand._",
            "",
            "| ID | Dataset | Publisher | Licence | Retrieved | URL |",
            "|---|---|---|---|---|---|",
        ]
        for r in self.records.values():
            lines.append(
                f"| `{r.id}` | {r.title} | {r.publisher} | {r.licence} | {r.retrieved} | {r.url or '_manual_'} |"
            )
        lines += ["", "## File checksums (SHA-256)", ""]
        for r in self.records.values():
            for f, h in r.files.items():
                lines.append(f"- `{f}` — `{h[:16]}…`")
        return "\n".join(lines) + "\n"
